/**
 * Начать подъём SDK сразу — из крошечного входа, до того как скачается игра.
 * Площадка не спешит убирать свою заглушку, пока игра молчит, а бандл весит
 * мегабайты. Адаптер потом ждёт этот же подъём, а не начинает второй.
 */
export function startSdkEarly(): void {
  const init = window.YaGames?.init();
  if (init === undefined) return;
  // Отказ разберёт адаптер; здесь — только чтобы он не всплыл как необработанный.
  init.catch(() => undefined);
  window.__yaSdkInit = init;
}
