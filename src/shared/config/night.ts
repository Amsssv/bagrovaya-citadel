import { z } from 'zod';

import raw from './night.json';

/**
 * Параметры расчёта ночи.
 *
 * `tickMs` — шаг симуляции. Это не правило игры, а разрешение расчёта: спека
 * задаёт скорострельность в выстрелах в секунду и скорость в клетках в секунду,
 * значит Рассвет непрерывен по времени и его надо чем-то дискретизировать.
 * Величина TODO_VERIFY: шаг должен быть достаточно мелким, чтобы результат от
 * него не плясал, — проверим прогоном бота на шаге 7.
 *
 * `maxSeconds` — предохранитель. Пока характеристики охотников стоят на нулях,
 * охотник со скоростью 0 не дойдёт до цитадели никогда, и без предела расчёт
 * повис бы. Ночь обрывается, результат честно помечается как оборванный.
 */
const NightConfigSchema = z.object({
  tickMs: z.int().positive(),
  maxSeconds: z.number().positive(),
});

export const NIGHT_CONFIG = NightConfigSchema.parse(raw);
