/**
 * Как фильтровать текстуру при отрисовке.
 *
 * Арт поля и атлас нарисованы крупнее, чем показываются: клетка поля — 200
 * точек, кадр атласа — 128, а на телефоне клетка — около сотни физических
 * пикселей. NEAREST при уменьшении берёт ближайшую точку и выбрасывает
 * остальные — тонкие детали рвутся, края рябят. LINEAR усредняет соседние.
 * Крупнее родного размера сглаживание, наоборот, мылит — там NEAREST.
 *
 * @param shown  сколько физических пикселей экрана занимает отрезок текстуры
 * @param native сколько точек этой текстуры в нём
 */
export function filterFor(shown: number, native: number): 'linear' | 'nearest' {
  if (shown <= 0 || native <= 0) return 'nearest';
  return shown < native ? 'linear' : 'nearest';
}
